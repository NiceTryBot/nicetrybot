// Single-request rules, judged at the edge. NiceTryBot sends each rule's WHERE as an expression tree
// (App\Data\EdgeExpression) on the gym triggers its verdicts lead to, along with what the trees need:
// path categories in the order they're tried, the hosting networks' ASNs, and each domain's other
// hostnames. Rules are data: a new or edited rule arrives on the next poll, with no rebuild.
//
// The edge only uses a rule to decide whether to ask NiceTryBot about a request before the client holds
// the rule's verdict. The gym check judges the rule again, so a slip here costs a round trip or a late
// verdict, never a wrong one. Evaluation follows App\Data\LiveRequest: a field the edge doesn't know
// makes a node unknown (nil); NOT of unknown is unknown, AND is false if either side is, OR is true if
// either side is. Only a rule that is surely true sends the request to NiceTryBot.
//
// testdata/live_rules.json, generated by NiceTryBot, holds rules and requests with what LiveRequest says
// of each; the tests hold this code to it.

// ruleExpr is one node of a rule's expression tree.
type ruleExpr struct {
	Kind    string            `json:"k"`
	Left    *ruleExpr         `json:"l"`
	Right   *ruleExpr         `json:"r"`
	Expr    *ruleExpr         `json:"e"`
	Field   string            `json:"f"`
	Op      string            `json:"op"`
	Value   json.RawMessage   `json:"v"`
	Pattern string            `json:"p"`
	Values  []json.RawMessage `json:"vs"`
	Neg     bool              `json:"neg"`
	Range   string            `json:"range"`

	// Compiled on decode.
	like   *regexp.Regexp
	value  string
	number float64
	isNum  bool
	set    map[string]bool
	prefix netip.Prefix
}

// edgeRule is a single-request rule a gym trigger carries.
type edgeRule struct {
	ID   int
	Expr *ruleExpr
}

// ruleEnv is what rule expressions need beyond the request: the path categories, in the order they're
// tried; the hosting networks' ASNs; and every domain's hostnames, by the hostname rules call it.
type ruleEnv struct {
	categories []pathCategory
	hosting    map[int64]bool
	hostKind   int
	canonical  map[string]string
}

type pathCategory struct {
	ID      int
	pattern *regexp.Regexp
}

// compile prepares a node for evaluation: LIKE patterns as regexps, values as strings (and numbers),
// sets for IN, prefixes for IP ranges. A node that can't be prepared becomes false.
func (e *ruleExpr) compile() {
	if e == nil {
		return
	}
	switch e.Kind {
	case "and", "or":
		if e.Left == nil || e.Right == nil {
			e.Kind = "false"
			return
		}
		e.Left.compile()
		e.Right.compile()
	case "not":
		if e.Expr == nil {
			e.Kind = "false"
			return
		}
		e.Expr.compile()
	case "cmp":
		e.value, e.number, e.isNum = rawValue(e.Value)
	case "like":
		quoted := regexp.QuoteMeta(strings.ToLower(e.Pattern))
		like, err := compilePattern("(?s)^" + strings.NewReplacer("%", ".*", "_", ".").Replace(quoted) + "$")
		if err != nil {
			// Too large a pattern; a panic here would take Caddy down from the poller.
			skippedPattern("rule", e.Pattern, err)
			e.Kind = "false"
			return
		}
		e.like = like
	case "in":
		e.set = map[string]bool{}
		for _, raw := range e.Values {
			value, _, _ := rawValue(raw)
			e.set[value] = true
		}
	case "cidr":
		prefix, err := netip.ParsePrefix(e.Range)
		if err != nil {
			e.Kind = "false"
			return
		}
		e.prefix = prefix.Masked()
	}
}

// rawValue reads a JSON string or number as the string PHP's loose comparison would match, and its
// number when it is one.
func rawValue(raw json.RawMessage) (string, float64, bool) {
	var s string
	if err := json.Unmarshal(raw, &s); err == nil {
		return s, 0, false
	}
	var n json.Number
	if err := json.Unmarshal(raw, &n); err == nil {
		f, err := n.Float64()
		return n.String(), f, err == nil
	}
	return string(raw), 0, false
}

// fact is one field of a request as rules see it: unknown, missing (nil), or a value.
type fact struct {
	known bool
	ok    bool
	text  string
	num   float64
	isNum bool
}

func unknown() fact               { return fact{} }
func missing() fact               { return fact{known: true} }
func textFact(s string) fact      { return fact{known: true, ok: true, text: s} }
func numberFact(n float64) fact   { return fact{known: true, ok: true, text: strconv.FormatFloat(n, 'f', -1, 64), num: n, isNum: true} }
func optionalText(s string) fact {
	if s == "" {
		return missing()
	}
	return textFact(s)
}

// requestFacts is a request as rules see it. Fields are worked out when first asked for.
type requestFacts struct {
	method, host, path, ip, ja4, ua, lang, tag string
	located                                    bool
	place                                      geoRecord
	env                                        *ruleEnv
	category                                   *fact
	// otherPaths are the request's other judged paths (see judgedPaths), after path.
	otherPaths []string
}

// factsFor describes a live request: the method, the domain's own hostname, the path, the client, its
// headers, the edge tag, and (when the edge knows the IP database) where it comes from.
func factsFor(r *http.Request, env *ruleEnv, geo *geoDB) *requestFacts {
	host := strings.ToLower(hostOnly(r.Host))
	if env != nil {
		if canonical, ok := env.canonical[host]; ok {
			host = canonical
		}
	}
	paths := judgedPaths(r)
	f := &requestFacts{
		method:     r.Method,
		host:       host,
		path:       paths[0],
		otherPaths: paths[1:],
		ip:         requestIP(r),
		ua:         r.UserAgent(),
		lang:       r.Header.Get("Accept-Language"),
		env:        env,
	}
	if repl, ok := r.Context().Value(caddy.ReplacerCtxKey).(*caddy.Replacer); ok {
		f.ja4 = repl.ReplaceAll("{tls.ja4}", "")
	}
	if tag, ok := caddyhttp.GetVar(r.Context(), "bot_tag").(string); ok {
		f.tag = tag
	}
	if geo != nil {
		f.place, f.located = geo.lookup(f.ip)
	}
	return f
}

// knownMethods are the verbs NiceTryBot names; any other is OTHER (App\Enums\HttpMethod).
var knownMethods = map[string]bool{"GET": true, "POST": true, "HEAD": true, "PUT": true, "PATCH": true, "DELETE": true, "OPTIONS": true, "CONNECT": true, "TRACE": true}

func (f *requestFacts) value(field string) fact {
	switch field {
	case "method":
		if verb := strings.ToUpper(f.method); knownMethods[verb] {
			return textFact(verb)
		}
		return textFact("OTHER")
	case "host":
		return textFact(f.host)
	case "path":
		return textFact(f.path)
	case "category":
		return f.categoryFact()
	case "ip":
		return optionalText(f.ip)
	case "ja4":
		return optionalText(f.ja4)
	case "ja4.alpn":
		if len(f.ja4) < 10 {
			return missing()
		}
		return textFact(f.ja4[8:10])
	case "ua":
		return optionalText(f.ua)
	case "lang":
		return optionalText(f.lang)
	case "tag":
		return optionalText(f.tag)
	}

	if !f.located {
		return unknown()
	}
	switch field {
	case "country":
		return optionalText(strings.ToUpper(f.place.country))
	case "region":
		return optionalText(f.place.region)
	case "city":
		return optionalText(f.place.city)
	case "asn":
		if f.place.asn == 0 {
			return missing()
		}
		return numberFact(float64(f.place.asn))
	case "network":
		return optionalText(firstRunes(f.place.network, 255))
	case "network.kind":
		if f.place.asn == 0 || f.env == nil {
			return missing()
		}
		if f.env.hosting[int64(f.place.asn)] {
			return numberFact(float64(f.env.hostKind))
		}
		return numberFact(0)
	}
	return unknown()
}

// categoryFact is the first category whose patterns match the path, or missing for an ordinary page.
func (f *requestFacts) categoryFact() fact {
	if f.category != nil {
		return *f.category
	}
	result := unknown()
	if f.env != nil && f.env.categories != nil {
		result = missing()
		for _, c := range f.env.categories {
			if c.pattern.MatchString(f.path) {
				result = numberFact(float64(c.ID))
				break
			}
		}
	}
	f.category = &result
	return result
}

// holds reports whether a rule is surely true of the request on any of the paths it's judged by, so
// /index.php/login can't slip past a rule about /login.
func (f *requestFacts) holds(e *ruleExpr) bool {
	if v := e.eval(f); v != nil && *v {
		return true
	}
	for _, p := range f.otherPaths {
		other := *f
		other.path, other.category, other.otherPaths = p, nil, nil
		if v := e.eval(&other); v != nil && *v {
			return true
		}
	}
	return false
}

// eval judges a node against a request: true, false, or nil when it hinges on something unknown.
func (e *ruleExpr) eval(f *requestFacts) *bool {
	switch e.Kind {
	case "true":
		return boolPtr(true)
	case "and":
		return and(e.Left.eval(f), e.Right.eval(f))
	case "or":
		return or(e.Left.eval(f), e.Right.eval(f))
	case "not":
		if v := e.Expr.eval(f); v != nil {
			return boolPtr(!*v)
		}
		return nil
	case "cmp":
		v := f.value(e.Field)
		if !v.known {
			return nil
		}
		if !v.ok {
			return boolPtr(false)
		}
		return boolPtr(compare(v, e.Op, e.value, e.number, e.isNum))
	case "like":
		v := f.value(e.Field)
		if !v.known {
			return nil
		}
		if !v.ok {
			return boolPtr(false)
		}
		return boolPtr(e.like.MatchString(strings.ToLower(v.text)) != e.Neg)
	case "in":
		v := f.value(e.Field)
		if !v.known {
			return nil
		}
		if !v.ok {
			return boolPtr(false)
		}
		return boolPtr(e.set[v.text] != e.Neg)
	case "cidr":
		if f.ip == "" {
			return nil
		}
		addr, err := netip.ParseAddr(f.ip)
		return boolPtr(err == nil && e.prefix.Contains(addr.Unmap()))
	case "null":
		v := f.value(e.Field)
		if !v.known {
			return nil
		}
		return boolPtr(!v.ok != e.Neg)
	}
	return boolPtr(false)
}

// compare follows PHP's loose comparison of a field's value with a rule's: numerically when both are
// numbers, as strings otherwise.
func compare(v fact, op, value string, number float64, isNum bool) bool {
	if v.isNum && isNum {
		switch op {
		case "=":
			return v.num == number
		case "!=":
			return v.num != number
		case "<":
			return v.num < number
		case "<=":
			return v.num <= number
		case ">":
			return v.num > number
		case ">=":
			return v.num >= number
		}
		return false
	}
	switch op {
	case "=":
		return v.text == value
	case "!=":
		return v.text != value
	case "<":
		return v.text < value
	case "<=":
		return v.text <= value
	case ">":
		return v.text > value
	case ">=":
		return v.text >= value
	}
	return false
}

func and(left, right *bool) *bool {
	switch {
	case left != nil && !*left, right != nil && !*right:
		return boolPtr(false)
	case left == nil, right == nil:
		return nil
	}
	return boolPtr(true)
}

func or(left, right *bool) *bool {
	switch {
	case left != nil && *left, right != nil && *right:
		return boolPtr(true)
	case left == nil, right == nil:
		return nil
	}
	return boolPtr(false)
}

func boolPtr(b bool) *bool { return &b }

func firstRunes(s string, n int) string {
	if utf8.RuneCountInString(s) <= n {
		return s
	}
	return string([]rune(s)[:n])
}

// ruleEnvFrom reads what rule expressions need from the triggers payload. Categories use Laravel's
// Str::is: `*` matches anything, case doesn't matter, and the whole path must match.
func ruleEnvFrom(payload map[string]json.RawMessage) *ruleEnv {
	env := &ruleEnv{hosting: map[int64]bool{}, canonical: map[string]string{}}

	var categories []struct {
		ID       int      `json:"id"`
		Patterns []string `json:"patterns"`
	}
	if raw, ok := payload["categories"]; ok && json.Unmarshal(raw, &categories) == nil {
		env.categories = []pathCategory{}
		for _, c := range categories {
			alternatives := make([]string, 0, len(c.Patterns))
			for _, p := range c.Patterns {
				alternatives = append(alternatives, strings.ReplaceAll(regexp.QuoteMeta(p), `\*`, ".*"))
			}
			if len(alternatives) == 0 {
				continue
			}
			pattern, err := compilePattern("(?is)^(?:" + strings.Join(alternatives, "|") + ")$")
			if err != nil {
				skippedPattern("path category", strconv.Itoa(c.ID), err)
				continue
			}
			env.categories = append(env.categories, pathCategory{ID: c.ID, pattern: pattern})
		}
	}

	var networks []struct {
		Kind int     `json:"kind"`
		ASNs []int64 `json:"asns"`
	}
	if raw, ok := payload["networks"]; ok && json.Unmarshal(raw, &networks) == nil {
		for _, n := range networks {
			env.hostKind = n.Kind
			for _, asn := range n.ASNs {
				env.hosting[asn] = true
			}
		}
	}

	var domains []struct {
		Hostname string   `json:"hostname"`
		Aliases  []string `json:"aliases"`
	}
	if raw, ok := payload["domains"]; ok && json.Unmarshal(raw, &domains) == nil {
		for _, d := range domains {
			for _, alias := range d.Aliases {
				env.canonical[strings.ToLower(alias)] = strings.ToLower(d.Hostname)
			}
		}
	}
	return env
}

// matchingRules lists the target's rules that are surely true of the request.
func (t *target) matchingRules(r *http.Request) []int {
	if len(t.Rules) == 0 {
		return nil
	}
	facts := factsFor(r, t.env, sharedGeo())
	var ids []int
	for _, rule := range t.Rules {
		if facts.holds(rule.Expr) {
			ids = append(ids, rule.ID)
		}
	}
	return ids
}

// gymRulesVar is where a request keeps the rules it matched, for the gym check to hear.
const gymRulesVar = "nicetry_gym_rules"

func rememberRules(r *http.Request, ids []int) {
	seen, _ := caddyhttp.GetVar(r.Context(), gymRulesVar).([]int)
	for _, id := range ids {
		found := false
		for _, s := range seen {
			if s == id {
				found = true
				break
			}
		}
		if !found {
			seen = append(seen, id)
		}
	}
	caddyhttp.SetVar(r.Context(), gymRulesVar, seen)
}

func rememberedRules(r *http.Request) []int {
	ids, _ := caddyhttp.GetVar(r.Context(), gymRulesVar).([]int)
	return ids
}
